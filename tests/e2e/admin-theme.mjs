// The admin theme button: follows the website theme at first, then keeps its own choice. No emulators needed (static server on :8765).
import { createRequire } from 'module';
import fs from 'fs';
const { chromium } = createRequire(process.env.NODE_PATH + '/')('playwright');
const SP = process.argv[2], FB = SP + '/fb/node_modules/firebase/';
const cfg = fs.readFileSync('/home/user/ohmygoal/config.js', 'utf8').replace(/firebase: \{[\s\S]*?\n    \},/, `firebase: { apiKey: 'fake-key', authDomain: 'demo-ohmygoal.firebaseapp.com', projectId: 'demo-ohmygoal', appId: '1:1:web:1' },`);
const b = await chromium.launch();
let bad = 0; const step = (n, ok, x = '') => { if (!ok) bad++; console.log(`${ok ? 'PASS' : 'FAIL'} ${n} ${x}`); };
const ctx = await b.newContext({ serviceWorkers: 'block', viewport: { width: 360, height: 700 } });
await ctx.route('**/config.js', r => r.fulfill({ body: cfg, contentType: 'text/javascript' }));
await ctx.route('https://www.gstatic.com/firebasejs/11.6.1/*', r => r.fulfill({ body: fs.readFileSync(FB + r.request().url().split('/').pop()), contentType: 'text/javascript' }));
await ctx.route(/jsdelivr|fonts\.g|country\.is|googleapis/, r => r.abort());
await ctx.addInitScript(() => { if (!sessionStorage.seeded) { localStorage.setItem('ac.theme', '"light"'); sessionStorage.seeded = '1'; } });
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:8765/admin.html');
await p.waitForSelector('#themeBtn');
const theme = () => p.evaluate(() => document.documentElement.dataset.theme);
step('follows the website theme at first (light)', await theme() === 'light' && (await p.textContent('#themeBtn')) === 'Dark mode');
await p.click('#themeBtn');
step('button switches to dark', await theme() === 'dark' && (await p.textContent('#themeBtn')) === 'Light mode');
const bg = await p.evaluate(() => getComputedStyle(document.body).backgroundColor);
await p.click('#themeBtn');
step('and back to light, the page colours change', await theme() === 'light' && bg !== await p.evaluate(() => getComputedStyle(document.body).backgroundColor), bg);
await p.reload(); await p.waitForSelector('#themeBtn');
step('the choice is remembered after reload', await theme() === 'light');
await p.click('#themeBtn'); await p.reload(); await p.waitForSelector('#themeBtn');
step('dark is remembered too, even though the website theme says light', await theme() === 'dark');
step('the website theme setting is left alone', await p.evaluate(() => localStorage.getItem('ac.theme')) === '"light"');
step('no sideways scroll on the phone', await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
step('no page errors', errs.length === 0, errs.join('|'));
await p.screenshot({ path: SP + '/admin-theme-dark.png' });
await b.close(); process.exit(bad ? 1 : 0);
