// Video group rooms: four per room, other people's video stays blurred until checked, the fifth person is told the room is full.
import { createRequire } from 'module';
import fs from 'fs';
const { chromium } = createRequire(process.env.NODE_PATH + '/')('playwright');
const cfg = fs.readFileSync('/home/user/ohmygoal/config.js', 'utf8').replace(/firebase: \{[\s\S]*?\n    \},/, 'firebase: null,');
const appSrc = fs.readFileSync('/home/user/ohmygoal/js/app.js', 'utf8') + '\nwindow.__t = { S };\n';
const browser = await chromium.launch({ args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
const errors = [];
let failures = 0;
const step = (n, ok, extra = '') => { if (!ok) failures++; console.log(`${ok ? 'PASS' : 'FAIL'} ${n} ${extra}`); };
const ctx = await browser.newContext({ permissions: ['camera', 'microphone'], serviceWorkers: 'block', viewport: { width: 1280, height: 900 } });
await ctx.route('**/config.js', r => r.fulfill({ body: cfg, contentType: 'text/javascript' }));
await ctx.route('**/js/app.js', r => r.fulfill({ body: appSrc, contentType: 'text/javascript' }));
await ctx.route(/jsdelivr|country\.is|fonts\.g/, r => r.abort());
await ctx.addInitScript(() => { localStorage.setItem('ac.ageVerifiedUntil', String(Date.now() + 864e5)); });
const open = async name => { const p = await ctx.newPage(); p.on('pageerror', e => errors.push(name + ': ' + e.message)); await p.goto('http://localhost:8765/index.html'); await p.waitForFunction(() => document.getElementById('startBtn').textContent === 'Start chatting'); await p.fill('#nickInput', name); await p.check('#ageCheck'); return p; };
const join = async p => { await p.click('#groupBtn'); await p.click('[data-gmode="video"]'); await p.click('#groupTopics .group-topic:has-text("Gaming")'); };
const names = ['Aarav', 'Meera', 'Kabir', 'Dev', 'Esha'];
const pages = [];
for (const n of names) pages.push(await open(n));
for (const p of pages.slice(0, 4)) { await join(p); await p.waitForSelector('#groupRoom:not(.hidden)', { timeout: 10000 }); }
const [a, b, c, d, e] = pages;
await a.waitForFunction(() => document.querySelectorAll('#groupGrid .g-tile').length === 4, null, { timeout: 10000 }).catch(() => {});
step('1a. four people fill a video room', await a.locator('#groupGrid .g-tile').count() === 4 && /Video/.test(await a.textContent('#groupTitle')));
step('1b. the camera button is shown in a video room', await a.isVisible('#gCam'));
step('1c. the other people’s video tiles start blurred (safety check pending)', await a.locator('.g-tile.has-video.checking:not(.self), .g-tile.has-video.hidden-video:not(.self)').count() >= 1 || await a.locator('.g-tile:not(.self) .g-video').count() === 0);
await join(e);
await e.waitForTimeout(1500);
step('2a. the fifth person is told the room is full and stays in the lobby', /room is full/.test(await e.textContent('#toasts')) && await e.isVisible('#groupLobby') && !(await e.isVisible('#groupRoom')));
step('2b. the room is still four', await a.locator('#groupGrid .g-tile').count() === 4);
await e.evaluate(() => 0);
const live = await e.evaluate(() => window.__t.S.localStream === null);
step('2c. the fifth person’s camera was released after the refusal', live);
await c.click('#groupLeave');
await e.click('#groupTopics .group-topic:has-text("Gaming")');
await e.waitForSelector('#groupRoom:not(.hidden)', { timeout: 10000 }).catch(() => {});
step('3a. once someone leaves there is space again', await e.isVisible('#groupRoom'));
await a.click('#gCam');
step('3b. the camera button turns your video off', (await a.getAttribute('#gCam', 'aria-pressed')) === 'true');
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no page errors');
console.log(failures ? `${failures} FAILED` : 'ALL PASSED');
await browser.close();
process.exit(failures ? 1 : 0);
